import { strToU8, zipSync } from 'fflate';
import { invoke } from '@tauri-apps/api/core';
import { save } from '@tauri-apps/plugin-dialog';
import type { RGB, Settings } from './engine';
import {
  loadMedia,
  disposeMedia,
  seekVideo,
  renderMedia,
  scaleCanvas,
  pngBytes,
  type Media,
} from './media';
import { saveBytes } from './platform';
import type { Stabilization } from './stabilization';

export type VideoFormat = 'frames' | 'webm' | 'mov';
export interface ExportOptions {
  fps: number;
  start: number;
  end: number;
  scale: number;
  format: VideoFormat;
  ffmpeg: string;
}
export interface Progress {
  fraction: number;
  label: string;
  encoding?: boolean;
}
export function frameTimes(start: number, end: number, fps: number) {
  if (
    !Number.isFinite(start) ||
    !Number.isFinite(end) ||
    !Number.isFinite(fps) ||
    start < 0 ||
    end <= start ||
    fps < 1 ||
    fps > 60
  )
    throw new Error('Choose a valid trim range and 1–60 FPS.');
  const count = Math.ceil((end - start) * fps - 1e-8);
  if (count > 1800)
    throw new Error(
      'This preview supports up to 1,800 frames per export. Shorten the trim range or reduce FPS.',
    );
  return Array.from({ length: count }, (_, i) => start + i / fps);
}
export async function exportVideo(
  media: Media,
  settings: Settings,
  palette: RGB[],
  options: ExportOptions,
  stabilization: Stabilization,
  signal: AbortSignal,
  progress: (p: Progress) => void,
) {
  if (!media.url) throw new Error('Open a video first.');
  const times = frameTimes(options.start, options.end, options.fps);
  const base = media.name.replace(/\.[^.]+$/, '').replace(/[^a-zA-Z0-9_-]/g, '_') || 'pixel-forge';
  let session: string | undefined;
  if (options.format !== 'frames') {
    const path = await save({
      defaultPath: `${base}-pixel.${options.format}`,
      filters: [
        {
          name: options.format === 'mov' ? 'ProRes 4444' : 'WebM VP9',
          extensions: [options.format],
        },
      ],
    });
    if (!path) return false;
    session = await invoke<string>('begin_encode', {
      output: path,
      fps: options.fps,
      format: options.format,
      ffmpeg: options.ffmpeg,
    });
  }
  let decoder: Media | undefined;
  try {
    // Isolated decoder leaves the preview and its current time untouched.
    const response = await fetch(media.url);
    const blob = await response.blob();
    decoder = await loadMedia(new File([blob], media.name, { type: blob.type }));
    const frames: Record<string, Uint8Array> = {};
    let total = 0;
    let width = 0,
      height = 0;
    for (let i = 0; i < times.length; i++) {
      signal.throwIfAborted();
      await seekVideo(decoder.source as HTMLVideoElement, times[i]);
      const { canvas } = renderMedia(decoder, settings, palette, stabilization, times[i]);
      const scaled = scaleCanvas(canvas, options.scale);
      width = scaled.width;
      height = scaled.height;
      const bytes = await pngBytes(scaled);
      signal.throwIfAborted();
      if (session)
        await invoke('write_encode_frame', { id: session, index: i, png: Array.from(bytes) });
      else {
        total += bytes.byteLength;
        if (total > 240 * 1024 * 1024)
          throw new Error(
            'Frame archive exceeds 240 MB. Use a shorter clip, smaller scale, or native video export.',
          );
        frames[`frames/frame-${String(i).padStart(6, '0')}.png`] = bytes;
      }
      progress({
        fraction: (i + 1) / times.length,
        label: `Rendering frame ${i + 1} of ${times.length}`,
      });
    }
    signal.throwIfAborted();
    if (session) {
      progress({ fraction: 1, label: 'Encoding video with FFmpeg…', encoding: true });
      await invoke('finish_encode', { id: session });
      session = undefined;
    } else {
      frames['manifest.json'] = strToU8(
        JSON.stringify(
          {
            app: 'Pixel Forge',
            version: 1,
            source: media.name,
            fps: options.fps,
            frameCount: times.length,
            width,
            height,
            start: options.start,
            end: options.end,
            timestamps: times,
            settings,
            palette,
            stabilization,
            alpha: 'RGBA PNG; preserves the alpha supplied by the preview decoder. No audio.',
            paletteReference: 'First source frame, fixed across the clip.',
          },
          null,
          2,
        ),
      );
      frames['README.txt'] = strToU8(
        `Pixel Forge frame sequence\n${times.length} RGBA PNG frames at ${options.fps} FPS, ${width} x ${height}.\nImport frames in numerical order. Timing and conversion settings are in manifest.json.\nAlpha is preserved if supplied by the source decoder or generated by color key. Audio is not included.\n`,
      );
      progress({ fraction: 1, label: 'Packing PNG frames…' });
      // PNG is already compressed. Store it to avoid recompressing on the UI thread.
      const bytes = zipSync(frames, { level: 0 });
      signal.throwIfAborted();
      return await saveBytes(bytes, `${base}-frames.zip`, 'zip');
    }
    return true;
  } finally {
    if (decoder) disposeMedia(decoder);
    if (session) await invoke('abort_encode', { id: session }).catch(() => {});
  }
}
